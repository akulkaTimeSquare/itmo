% 1. Объявление символьной переменной для частоты
syms w real; % Предположение, что w - вещественное число, помогает упрощению

% 2. Определение матриц системы
A = [3, 1; 1, 1];
B = [1; 2];
K = [-86.027, 7.192];
Bf = [3; 4];

% 3. Расчет матрицы замкнутой системы A_m
Am = A + B*K;

% 4. Построение передаточной функции G(jw)
% G(jw) = (jw*I - A_m)^-1 * B_f
I = eye(size(A));
s = 1i*w;
G_jw = (s*I - Am) \ Bf; % Используем '\' (mldivide) - это более надежно, чем inv()

% 5. Расчет квадрата сингулярного числа
% Для вектора это квадрат его евклидовой нормы: G_jw' * G_jw
sigma_sq = G_jw' * G_jw;

% 6. Упрощение выражения для квадрата сингулярного числа
simplified_sigma_sq = simplify(sigma_sq);

% 7. Получение итоговой формулы для sigma(w)
sigma_w = sqrt(simplified_sigma_sq);

% 8. Вывод результата в удобном для чтения виде
disp('Упрощенная формула для sigma(w):');
pretty(sigma_w);
